import ipywidgets as widgets
from IPython.display import display, HTML
import importlib, tictactoe
importlib.reload(tictactoe)
from tictactoe import *

display(HTML("""
<style>
.ttt button { font-size: 40px !important; background: black !important;
              color: white !important; border: 2px solid white !important; }
.ttt button:disabled { opacity: 1 !important; }
</style>"""))

game = {"board": initial_state(), "user": None}

title = widgets.HTML()
cells = [[widgets.Button(description=" ",
                         layout=widgets.Layout(width="90px", height="90px"))
          for _ in range(3)] for _ in range(3)]
for row in cells:
    for c in row:
        c.add_class("ttt")

btn_x = widgets.Button(description="Play as X")
btn_o = widgets.Button(description="Play as O")
btn_again = widgets.Button(description="Play Again")

def set_title(text):
    title.value = f"<h2 style='font-family:sans-serif'>{text}</h2>"

def refresh():
    board = game["board"]
    over = terminal(board)
    for i in range(3):
        for j in range(3):
            cells[i][j].description = board[i][j] if board[i][j] else " "
            cells[i][j].disabled = (board[i][j] is not EMPTY or over
                                    or game["user"] is None
                                    or player(board) != game["user"])
    if game["user"] is None:
        set_title("Choose your side")
    elif over:
        w = winner(board)
        set_title(f"Game Over: {w} wins." if w else "Game Over: It's a tie.")
    elif player(board) == game["user"]:
        set_title(f"Your turn ({game['user']})")
    else:
        set_title("AI is thinking...")

def ai_move():
    board = game["board"]
    if not terminal(board) and player(board) != game["user"]:
        game["board"] = result(board, minimax(board))

def on_click(i, j):
    def handler(_):
        game["board"] = result(game["board"], (i, j))
        refresh()
        ai_move()
        refresh()
    return handler

for i in range(3):
    for j in range(3):
        cells[i][j].on_click(on_click(i, j))

def start(user):
    game["board"] = initial_state()
    game["user"] = user
    refresh()
    ai_move()      # if you chose O, the AI (X) moves first
    refresh()

btn_x.on_click(lambda _: start(X))
btn_o.on_click(lambda _: start(O))
btn_again.on_click(lambda _: (game.update(board=initial_state(), user=None), refresh()))

grid = widgets.GridBox([c for row in cells for c in row],
                       layout=widgets.Layout(grid_template_columns="repeat(3, 90px)"))
display(widgets.VBox([title, widgets.HBox([btn_x, btn_o]), grid, btn_again]))
refresh()